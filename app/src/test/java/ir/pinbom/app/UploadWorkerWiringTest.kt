package ir.pinbom.app

import dagger.multibindings.StringKey
import ir.pinbom.app.work.UploadWorker
import ir.pinbom.app.work.UploadWorker_AssistedFactory
import ir.pinbom.app.work.UploadWorker_HiltModule
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNotNull
import org.junit.Test

/**
 * The wiring that makes an upload actually start.
 *
 * `UploadWorker` is a `@HiltWorker`: it is injected (repository, session, image
 * preparation), so it cannot be constructed by WorkManager's default factory —
 * that one only knows the two-argument constructor and fails with
 * `NoSuchMethodException`, which is what a pin upload used to die of, silently,
 * a moment after it was queued.
 *
 * `HiltWorkerFactory` looks the worker up in a map generated by kapt, keyed by the
 * worker's fully-qualified name. Both halves of that contract are asserted here:
 *
 *   · the generated assisted factory exists (the processor ran at all), and
 *   · the map key is exactly the class name WorkManager will ask for.
 *
 * Referencing these types is itself the guard: drop `androidx.hilt:hilt-compiler`
 * from the build and this file stops compiling.
 */
class UploadWorkerWiringTest {

    @Test
    fun `the assisted factory for the upload worker was generated`() {
        assertNotNull(UploadWorker_AssistedFactory::class.java)
    }

    @Test
    fun `the worker map is keyed by the name WorkManager asks for`() {
        val bind = UploadWorker_HiltModule::class.java.declaredMethods
            .firstOrNull { it.name == "bind" }
        assertNotNull("HiltWorkerFactory's map binding is missing", bind)

        val key = bind!!.getAnnotation(StringKey::class.java)
        assertNotNull("the map binding carries no key", key)
        assertEquals(
            "the key must be the class name HiltWorkerFactory looks up",
            UploadWorker::class.java.name,
            key!!.value,
        )
    }
}
